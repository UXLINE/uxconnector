declare(strict_types=1);

namespace GlpiPlugin\Uxconnector\Domain\Engine\Http;

enum HttpMethod: string
{
    case GET = 'GET';
    case POST = 'POST';
    case PUT = 'PUT';
    case PATCH = 'PATCH';
    case DELETE = 'DELETE';

    public function allowsRequestBody(): bool
    {
        return $this !== self::GET;
    }
}
